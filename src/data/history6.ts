export type Source = { page: number };

export type ChoiceQuestion = {
  id: string;
  kind: 'single' | 'multiple';
  title: string;
  prompt: string;
  options: string[];
  correct: number[];
  points: number;
  source: Source;
  explanation: string;
};

export type OrderQuestion = {
  id: string;
  kind: 'order';
  title: string;
  prompt: string;
  options: { id: string; label: string }[];
  correct: string[];
  points: number;
  source: Source;
  explanation: string;
};

export type NumberQuestion = {
  id: string;
  kind: 'number';
  title: string;
  prompt: string;
  correct: number;
  points: number;
  explanation: string;
};

export type SelfCheckQuestion = {
  id: string;
  kind: 'self-check';
  title: string;
  prompt: string;
  checklist: string[];
  points: number;
};

export type Question = ChoiceQuestion | OrderQuestion | NumberQuestion | SelfCheckQuestion;

